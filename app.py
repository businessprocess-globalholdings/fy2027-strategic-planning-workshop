def query(sql, args=()):
    with db() as con:
        if using_supabase():
            sql = sql.replace("?", "%s")
        return [dict(r) for r in con.execute(sql, args).fetchall()]


def write(sql, args=()):
    with db() as con:
        if using_supabase():
            sql = sql.replace("?", "%s")
            returns_id = sql.lstrip().upper().startswith("INSERT INTO V2_OBJECTIVES")
            if returns_id:
                sql += " RETURNING id"
            cur = con.execute(sql, args)
            if returns_id:
                row = cur.fetchone()
                return row["id"] if row else None
            return None
        cur = con.execute(sql, args)
        return cur.lastrowid


