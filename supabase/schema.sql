-- FY2027 workshop tables. Run this in Supabase SQL Editor before setting DATABASE_URL.
create table if not exists v2_swot (
  id bigint generated by default as identity primary key,
  department text not null,
  quadrant text not null check (quadrant in ('Strength','Weakness','Opportunity','Threat')),
  factor text not null
);

create table if not exists v2_objectives (
  id bigint generated by default as identity primary key,
  department text not null,
  goal text not null,
  improvement double precision,
  baseline double precision,
  target double precision,
  unit text not null default '',
  deadline date not null,
  perspective text not null check (perspective in ('Organizational Capacity','Internal Process','Customer and Stakeholder Value','Financial Value')),
  created_at timestamptz not null default now()
);

create table if not exists v2_tows_links (
  id bigint generated by default as identity primary key,
  objective_id bigint not null references v2_objectives(id) on delete cascade,
  swot_a bigint not null references v2_swot(id) on delete cascade,
  swot_b bigint not null references v2_swot(id) on delete cascade,
  unique (objective_id, swot_a, swot_b)
);

create table if not exists v2_arrows (
  id bigint generated by default as identity primary key,
  department text not null,
  source_id bigint not null references v2_objectives(id) on delete cascade,
  target_id bigint not null references v2_objectives(id) on delete cascade,
  line_type text not null check (line_type in ('Straight arrow','Broken line arrow')),
  unique (department, source_id, target_id)
);

create table if not exists v2_scorecard (
  objective_id bigint primary key references v2_objectives(id) on delete cascade,
  actual double precision,
  fy26_target double precision,
  deprioritized boolean not null default false,
  frequency text not null default '',
  owner text not null default '',
  owner_department text not null default ''
);

alter table v2_scorecard add column if not exists fy26_target double precision;
alter table v2_scorecard add column if not exists deprioritized boolean not null default false;

create index if not exists v2_swot_department_quadrant_idx on v2_swot(department, quadrant);
create index if not exists v2_objectives_department_idx on v2_objectives(department);
create index if not exists v2_arrows_department_idx on v2_arrows(department);
create index if not exists v2_scorecard_owner_department_idx on v2_scorecard(owner_department);
